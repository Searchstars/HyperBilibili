import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const inputPath = resolve(root, ".astroforge/tailwind.vela.input.css");
const rawOutputPath = resolve(root, ".astroforge/tailwind.vela.raw.css");
const outputPath = resolve(root, "src/vela-tailwind.css");
const tailwindBin = resolve(root, "node_modules/.bin/tailwindcss");

mkdirSync(dirname(inputPath), { recursive: true });

writeFileSync(
  inputPath,
  [
    '@import "tailwindcss";',
    '@source "../src/**/*.tsx";',
    "",
  ].join("\n"),
);

execFileSync(tailwindBin, ["-i", inputPath, "-o", rawOutputPath], {
  cwd: root,
  stdio: "inherit",
});

const css = readFileSync(rawOutputPath, "utf8");
const variables = extractThemeVariables(css);
const utilities = extractLayer(css, "utilities");
const rules = extractClassRules(utilities)
  .map((rule) => ({
    selector: rule.selector,
    declarations: rule.declarations.map(([name, value]) => [
      name,
      normalizeValue(resolveCssVariables(value, variables)),
    ]),
  }))
  .filter((rule) => rule.declarations.length > 0);

const output = [
  "/* Generated by scripts/generate-vela-tailwind.mjs. Do not edit by hand. */",
  ...rules.map(formatRule),
  "",
].join("\n\n");

writeFileSync(outputPath, output);

function extractThemeVariables(source) {
  const theme = extractLayer(source, "theme");
  const variables = new Map();

  for (const match of theme.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    variables.set(match[1], match[2].trim());
  }

  return variables;
}

function extractLayer(source, name) {
  const marker = `@layer ${name}`;
  const start = source.indexOf(marker);

  if (start === -1) return "";

  const open = source.indexOf("{", start);
  if (open === -1) return "";

  const close = findMatchingBrace(source, open);
  return close === -1 ? "" : source.slice(open + 1, close);
}

function extractClassRules(source) {
  const rules = [];
  let index = 0;

  while (index < source.length) {
    const selectorStart = source.indexOf(".", index);
    if (selectorStart === -1) break;

    const open = source.indexOf("{", selectorStart);
    if (open === -1) break;

    const selector = source.slice(selectorStart, open).trim();
    const close = findMatchingBrace(source, open);
    if (close === -1) break;

    if (isSimpleClassSelector(selector)) {
      rules.push({
        selector,
        declarations: parseDeclarations(source.slice(open + 1, close)),
      });
    }

    index = close + 1;
  }

  return rules;
}

function isSimpleClassSelector(selector) {
  return /^\.(-?[_a-zA-Z]+[_a-zA-Z0-9-]*|[A-Za-z0-9_-]+)$/.test(selector);
}

function parseDeclarations(body) {
  return body
    .split(";")
    .map((item) => item.trim())
    .filter(Boolean)
    .map((item) => {
      const colon = item.indexOf(":");
      if (colon === -1) return undefined;

      return [
        item.slice(0, colon).trim(),
        item.slice(colon + 1).trim(),
      ];
    })
    .filter(Boolean);
}

function resolveCssVariables(value, variables, seen = new Set()) {
  return value.replace(/var\((--[\w-]+)\)/g, (_, name) => {
    if (seen.has(name)) return `var(${name})`;

    seen.add(name);
    const resolved = variables.get(name);
    return resolved ? resolveCssVariables(resolved, variables, seen) : `var(${name})`;
  });
}

function normalizeValue(value) {
  let normalized = value
    .replace(/\b0?\.25rem\b/g, "4px")
    .replace(/\b0?\.5rem\b/g, "8px");

  normalized = normalized.replace(
    /calc\(\s*([0-9.]+)px\s*\*\s*([0-9.]+)\s*\)/g,
    (_, size, factor) => `${Number(size) * Number(factor)}px`,
  );

  normalized = normalized.replace(
    /oklch\(\s*([0-9.]+)%\s+([0-9.]+)\s+([0-9.]+)\s*\)/g,
    (_, lightness, chroma, hue) =>
      oklchToHex(Number(lightness) / 100, Number(chroma), Number(hue)),
  );

  return normalized;
}

function formatRule(rule) {
  return [
    `${rule.selector} {`,
    ...rule.declarations.map(([name, value]) => `    ${name}: ${value};`),
    "}",
  ].join("\n");
}

function findMatchingBrace(source, openIndex) {
  let depth = 0;

  for (let index = openIndex; index < source.length; index += 1) {
    const char = source[index];

    if (char === "{") depth += 1;
    if (char === "}") depth -= 1;
    if (depth === 0) return index;
  }

  return -1;
}

function oklchToHex(lightness, chroma, hueDegrees) {
  const hue = (hueDegrees * Math.PI) / 180;
  const a = Math.cos(hue) * chroma;
  const b = Math.sin(hue) * chroma;

  const l_ = lightness + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = lightness - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = lightness - 0.0894841775 * a - 1.291485548 * b;

  const l = l_ ** 3;
  const m = m_ ** 3;
  const s = s_ ** 3;

  const red = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s;
  const green = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s;
  const blue = -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s;

  return `#${toSrgbByte(red)}${toSrgbByte(green)}${toSrgbByte(blue)}`;
}

function toSrgbByte(linear) {
  const value =
    linear >= 0.0031308
      ? 1.055 * linear ** (1 / 2.4) - 0.055
      : 12.92 * linear;

  return Math.round(clamp(value, 0, 1) * 255)
    .toString(16)
    .padStart(2, "0");
}

function clamp(value, min, max) {
  return Math.min(Math.max(value, min), max);
}
