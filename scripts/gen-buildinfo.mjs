import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");

function safe(cmd, fallback = "unknown") {
  try {
    return execSync(cmd, { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return fallback;
  }
}

const commit = safe("git rev-parse --short HEAD");
const branch = safe("git rev-parse --abbrev-ref HEAD");
const dirty = safe("git status --porcelain").length > 0 ? "+dirty" : "";
const buildTime = new Date().toISOString();
const mode = process.env.HB_MODE === "release" ? "release" : "dev";

const out = [
  "// Generated by scripts/gen-buildinfo.mjs. Do not edit by hand.",
  "",
  "export const BUILD_INFO = {",
  `  commit: ${JSON.stringify(commit + dirty)},`,
  `  branch: ${JSON.stringify(branch)},`,
  `  buildTime: ${JSON.stringify(buildTime)},`,
  `  mode: ${JSON.stringify(mode)},`,
  "} as const;",
  "",
].join("\n");

writeFileSync(resolve(root, "src/shared/buildinfo.ts"), out);
console.log("[buildinfo]", commit + dirty, branch, buildTime, mode);
